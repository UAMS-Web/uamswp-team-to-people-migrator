			</label>
			<p>
				<button type="submit" name="uamswp_t2p_action" value="preview" class="button button-secondary">
					<?php esc_html_e('Preview (dry run - no changes made)', 'uamswp-t2p'); ?>
				</button>
				<button type="submit" name="uamswp_t2p_action" value="run" class="button button-primary" onclick="return confirm('<?php echo esc_js(__('This will create new People Showcase entries. The matching Team Showcase entries will be left untouched. Continue?', 'uamswp-t2p')); ?>');">
					<?php esc_html_e('Run Migration', 'uamswp-t2p'); ?>
				</button>
			</p>
		</form>

		<?php if ($results !== []) { ?>
