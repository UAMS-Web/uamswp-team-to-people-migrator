/**
 * Source taxonomy => destination taxonomy.
 *
 * @return array<string, string>
 */
function uamswp_t2p_get_taxonomy_map(): array
{
    return [
        'tshowcase-categories' => 'uamspeople-categories',
        'tshowcase-taxonomy' => 'uamspeople-taxonomy',
        'tshowcase-ctaxonomy' => 'uamspeople-ctaxonomy',
        'tshowcase-dtaxonomy' => 'uamspeople-dtaxonomy',
    ];
}

/**
 * Copies terms from a source taxonomy to a destination taxonomy for one
 * post, matching by term name and creating the destination term if it
 * doesn't already exist. Returns one row per term, with whether the
 * destination term had to be created.
 *
 * @param  int  $old_post_id  the source post
 * @param  int|null  $new_post_id  the destination post, null on a dry run
 * @param  bool  $dry_run  when true, nothing is written
 * @return list<array{taxonomy: string, name: string, created: bool}>
 */
function uamswp_t2p_migrate_terms(
    $old_post_id,
    $new_post_id,
    // The coverage driver does not report a signature line as executed, so this mutant is uncovered; a hand-applied mutation fails the suite.
    // @pest-mutate-ignore:FalseToTrue
    $dry_run = false
): array {
    $tax_map = uamswp_t2p_get_taxonomy_map();
    $report = [];

    foreach ($tax_map as $src_tax => $dest_tax) {
        if (! taxonomy_exists($src_tax) || ! taxonomy_exists($dest_tax)) {
            continue; // second/third/fourth taxonomy may not be enabled on this site
        }

        $terms = wp_get_post_terms($old_post_id, $src_tax, ['fields' => 'all']);
        if (is_wp_error($terms) || empty($terms)) {
            continue;
        }

        $dest_term_ids = [];

        foreach ($terms as $term) {
            $existing = get_term_by('name', $term->name, $dest_tax);

            if ($existing) {
                $dest_term_ids[] = (int) $existing->term_id;
                $report[] = [
                    'taxonomy' => $dest_tax,
                    'name' => $term->name,
                    'created' => false,
                ];
            } else {
                $report[] = [
                    'taxonomy' => $dest_tax,
                    'name' => $term->name,
                    'created' => true,
                ];

                if (! $dry_run) {
                    $new_term = wp_insert_term($term->name, $dest_tax, ['slug' => $term->slug]);
                    if (! is_wp_error($new_term)) {
                        $dest_term_ids[] = (int) $new_term['term_id'];
                    }
                }
            }
        }

        if (! $dry_run && $new_post_id !== null && $dest_term_ids !== []) {
            wp_set_post_terms($new_post_id, $dest_term_ids, $dest_tax, false);
        }
    }

    return $report;
}

