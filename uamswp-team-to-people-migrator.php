/**
 * Source posts still waiting to be migrated.
 *
 * @param  int  $limit  how many to fetch, -1 for all
 * @param  bool  $force  include posts already migrated
 * @return array<int, WP_Post>
 */
function uamswp_t2p_get_pending_posts(
    // The coverage driver does not report a signature line as executed, so this mutant is uncovered; a hand-applied mutation fails the suite.
    // @pest-mutate-ignore:DecrementInteger
    // @pest-mutate-ignore:IncrementInteger
    $limit = -1,
    // The coverage driver does not report a signature line as executed, so this mutant is uncovered; a hand-applied mutation fails the suite.
    // @pest-mutate-ignore:FalseToTrue
    $force = false
) {
    $args = [
        'post_type' => UAMSWP_T2P_SRC_CPT,
        'post_status' => 'any',
        'posts_per_page' => $limit,
        'orderby' => 'ID',
        'order' => 'ASC',
    ];

    if (! $force) {
        $args['meta_query'] = [
            [
                'key' => UAMSWP_T2P_MIGRATED_FLAG_OLD,
                'compare' => 'NOT EXISTS',
            ],
        ];
    }

    return get_posts($args);
}

/**
 * Generates a default "Last, First" sort string from the post title, the
 * same way both plugins auto-generate their internal lastname field.
 * People Showcase's _pssorttext is a manually-edited field with no
 * source equivalent in Team Showcase, so this gives a sane starting
 * point - flagged in the report as worth a human glance (titles with
 * suffixes like "Jr." or credentials like "MD" can split oddly).
 *
 * @param  string  $title  the post title
 * @return string
 */
function uamswp_t2p_guess_sorttext($title)
{
    $pieces = explode(' ', trim($title));
    if (count($pieces) < 2) {
        return $title;
    }
    $last = array_pop($pieces);

    return $last.', '.implode(' ', $pieces);
}

/**
 * Builds a full preview/result record for one post without necessarily
 * writing anything (when $dry_run is true).
 *
 * @param  int  $old_post_id  the source post
 * @param  bool  $dry_run  when true, nothing is written
 * @return WP_Error|array{old_id: int, title: string, new_id: int|null, meta_mapped: array<string, string>, meta_unmapped: array<string, string>, terms: list<array{taxonomy: string, name: string, created: bool}>, thumbnail: int, warnings?: list<string>}
 */
function uamswp_t2p_migrate_post(
    $old_post_id,
    // The coverage driver does not report a signature line as executed, so this mutant is uncovered; a hand-applied mutation fails the suite.
    // @pest-mutate-ignore:TrueToFalse
    $dry_run = true
): WP_Error|array {
    $old_post = get_post($old_post_id);
    if (! $old_post || $old_post->post_type !== UAMSWP_T2P_SRC_CPT) {
        return new WP_Error('invalid_post', 'Not a tshowcase post.');
    }

    $result = [
        'old_id' => $old_post_id,
        'title' => $old_post->post_title,
        'new_id' => null,
        'meta_mapped' => [],
        'meta_unmapped' => uamswp_t2p_get_unmapped_meta($old_post_id),
        'terms' => [],
        'thumbnail' => (int) get_post_thumbnail_id($old_post_id),
    ];

    if (! empty($result['meta_unmapped'])) {
        $result['warnings'][] = sprintf(
            '%d field(s) have no default equivalent in People Showcase and were copied as raw postmeta - review whether they need a matching entry in the People Showcase "Custom Fields" setting: %s',
            count($result['meta_unmapped']),
            implode(', ', array_keys($result['meta_unmapped']))
        );
    }

    $new_post_id = null;

    if (! $dry_run) {
        $postarr = [
            'post_type' => UAMSWP_T2P_DEST_CPT,
            'post_title' => $old_post->post_title,
            'post_content' => $old_post->post_content,
            'post_excerpt' => $old_post->post_excerpt,
            'post_status' => $old_post->post_status,
            'menu_order' => $old_post->menu_order,
            'post_author' => (int) $old_post->post_author,
            'post_date' => $old_post->post_date,
            'post_date_gmt' => $old_post->post_date_gmt,
        ];

        $new_post_id = wp_insert_post($postarr, true);

        if (is_wp_error($new_post_id)) {
            $result['warnings'][] = 'Failed to create new post: '.$new_post_id->get_error_message();

            return $result;
        }

        $result['new_id'] = $new_post_id;

        // Featured image
        if ($result['thumbnail']) {
            set_post_thumbnail($new_post_id, $result['thumbnail']);
        }
    }

    // Mapped custom fields
    $map = uamswp_t2p_get_field_map();
    foreach ($map as $dest_key => $spec) {
        [$src_key, $transform] = $spec;
        $value = get_post_meta($old_post_id, $src_key, true);

        if ($value === '' || $value === false) {
            continue;
        }

        // Every transform in the field map names a function defined in this file, so the operands agree whenever one is set.
        // @pest-mutate-ignore:BooleanAndToBooleanOr
        if ($transform && function_exists($transform)) {
            $value = call_user_func($transform, $value);
        }

        $result['meta_mapped'][$dest_key] = $value;

        if (! $dry_run) {
            update_post_meta($new_post_id, $dest_key, $value);
        }
    }

    // Sort text default
    $sorttext = uamswp_t2p_guess_sorttext($old_post->post_title);
    $result['meta_mapped']['_pssorttext'] = $sorttext;
    if (! $dry_run) {
        update_post_meta($new_post_id, '_pssorttext', $sorttext);
    }
    $result['warnings'][] = 'Sort Text ("'.$sorttext.'") was auto-generated from the title - worth a quick check for names with suffixes or credentials.';

    // Raw unmapped meta, copied with _ps prefix so nothing is lost
    foreach ($result['meta_unmapped'] as $src_key => $value) {
        if ($value === '') {
            continue;
        }
        $dest_key = '_ps'.substr($src_key, 3); // swap _ts -> _ps
        if (! $dry_run) {
            update_post_meta($new_post_id, $dest_key, $value);
        }
    }

    // Taxonomies
    $result['terms'] = uamswp_t2p_migrate_terms($old_post_id, $new_post_id, $dry_run);

    if (! $dry_run) {
        update_post_meta($new_post_id, UAMSWP_T2P_MIGRATED_FLAG_NEW, $old_post_id);
        update_post_meta($old_post_id, UAMSWP_T2P_MIGRATED_FLAG_OLD, $new_post_id);

        // Source post is intentionally left as-is - no status change, no edits.
    }

    return $result;
}

/* -----------------------------------------------------------------------
 * Shortcode finder & updater
 *
 * Renames [show-team...] shortcodes to [show-people...] wherever they
 * appear in post_content (any post type/status except Trash) and in the
 * two core text-based widgets. The main [show-team] shortcode is the
 * only one that takes post-ID lists (ids="" / exclude=""), so those are
 * translated through the migration mapping built up by
 * uamswp_t2p_migrate_post() - a Team post ID in that attribute becomes
 * the matching People post ID if (and only if) that post has already
 * been migrated.
 *
 * Note: this scans post_content and the classic Text/Custom HTML widgets.
 * If the site builds pages with a page builder that stores shortcodes
 * somewhere other than post_content, those won't be caught here.
 * --------------------------------------------------------------------- */
/**
 * Old tshowcase ID => new uamspeople ID, for every post migrated so far.
 *
 * @return int[]
 */
function uamswp_t2p_build_id_map(): array
{
    global $wpdb;

    $rows = $wpdb->get_results(
        $wpdb->prepare(
            "SELECT post_id, meta_value FROM {$wpdb->postmeta} WHERE meta_key = %s",
            UAMSWP_T2P_MIGRATED_FLAG_NEW
        )
    );

    $map = [];
    foreach ($rows as $row) {
        // The meta value was written from an integer post ID, so it is already a canonical decimal string and PHP casts the key itself.
        // @pest-mutate-ignore:RemoveIntegerCast
        $old_id = (int) $row->meta_value;
        $map[$old_id] = (int) $row->post_id; // old_id => new_id
    }

    return $map;
}

/**
 * Renames the shortcode tag itself: show-team, show-team-search,
 * show-team-users, show-team-count, show-team-info (opening and, just in
 * case, closing tags) -> their show-people equivalents. Longer/more
 * specific suffixes are matched first so "show-team-search" doesn't get
 * mangled by a bare "show-team" replacement.
 *
 * @param  string  $content  the content to rewrite
 */
function uamswp_t2p_rename_shortcode_tags($content): ?string
{
    return preg_replace(
        '/\[(\/?)show-team(-search|-users|-count|-info)?\b/',
        '[$1show-people$2',
        $content
    );
}

/**
 * Within ids="" / exclude="" attribute values on the main shortcode,
 * translates comma-separated Team post IDs to their new People post IDs.
 * IDs with no migration record yet are left as-is and reported back so
 * they can be reviewed by hand.
 *
 * @param  string  $content  the content to rewrite
 * @param  array<int, int|string>  $id_map  old post ID => new post ID
 * @param  list<string>  $untranslated  filled with the IDs that had no mapping
 */
function uamswp_t2p_translate_id_attributes($content, $id_map, &$untranslated): ?string
{
    $untranslated = [];

    $callback = function ($matches) use ($id_map, &$untranslated): string {
        $attr = $matches[1];
        $quote = $matches[2];
        $ids = array_map(trim(...), explode(',', $matches[3]));
        $new = [];

        foreach ($ids as $id) {
            if (! ctype_digit($id)) {
                $new[] = $id; // not a plain numeric ID, leave untouched

                continue;
            }
            if (isset($id_map[(int) $id])) {
                $new[] = $id_map[(int) $id];
            } else {
                $new[] = $id; // no migration record yet - leave as-is
                $untranslated[] = $id;
            }
        }

        return $attr.'='.$quote.implode(',', $new).$quote;
    };

    return preg_replace_callback(
        '/\b(ids|exclude)\s*=\s*(["\'])([0-9,\s]+)\2/',
        $callback,
        $content
    );
}

/**
 * Whether the content holds a show-team shortcode.
 *
 * @param  string  $content  the content to check
 */
function uamswp_t2p_content_has_shortcode($content): bool
{
    // The file is not strict_types, so the bool return type coerces preg_match()'s 0 or 1 itself and the cast changes nothing.
    // @pest-mutate-ignore:RemoveBooleanCast
    return (bool) preg_match('/\[show-team\b/', $content);
}

/**
 * Locations to check: post_content on any non-trashed post, plus the
 * classic Text and Custom HTML widgets.
 *
 * @return list<array{type: 'post', id: int, title: string, post_type: string, edit_link: string|null, matches: array<int, string>}|array{type: 'widget', id: string, title: string, post_type: string, edit_link: string, matches: array<int, string>}>
 */
function uamswp_t2p_scan_shortcode_locations(): array
{
    global $wpdb;

    $locations = [];

    $posts = $wpdb->get_results(
        "SELECT ID, post_title, post_type, post_content FROM {$wpdb->posts}
		 WHERE post_status != 'trash' AND post_content LIKE '%show-team%'"
    );

    foreach ($posts as $p) {
        if (! uamswp_t2p_content_has_shortcode($p->post_content)) {
            continue; // LIKE match was incidental (e.g. text mentioning "show-team" without brackets)
        }
        preg_match_all('/\[show-team[^\]]*\]/', $p->post_content, $found);
        $locations[] = [
            'type' => 'post',
            'id' => (int) $p->ID,
            'title' => $p->post_title,
            'post_type' => $p->post_type,
            'edit_link' => get_edit_post_link($p->ID),
            'matches' => $found[0],
        ];
    }

    foreach (['widget_text', 'widget_custom_html'] as $option_name) {
        $widgets = get_option($option_name);
        if (! is_array($widgets)) {
            continue;
        }
        foreach ($widgets as $key => $widget) {
            if (! is_array($widget)) {
                continue;
            }
            // A widget with neither field gets the placeholder, and no placeholder contains a show-team tag, so the next check skips it all the same.
            // @pest-mutate-ignore:EmptyStringToNotEmpty
            $text = $widget['content'] ?? $widget['text'] ?? '';
            if (! is_string($text) || ! uamswp_t2p_content_has_shortcode($text)) {
                continue;
            }
            preg_match_all('/\[show-team[^\]]*\]/', $text, $found);
            $locations[] = [
                'type' => 'widget',
                'id' => $option_name.':'.$key,
                'title' => sprintf('%s widget #%s', $option_name, $key),
                'post_type' => '',
                'edit_link' => admin_url('widgets.php'),
                'matches' => $found[0],
            ];
        }
    }

    return $locations;
}

/**
 * Applies the tag rename + ID translation to every location found by
 * uamswp_t2p_scan_shortcode_locations(). Returns the same structure with
 * an added 'updated' (bool) and 'untranslated_ids' per location.
 *
 * @return list<array{type: 'post', id: int, title: string, post_type: string, edit_link: string|null, matches: array<int, string>, updated: bool, untranslated_ids: list<string>}|array{type: 'widget', id: string, title: string, post_type: string, edit_link: string, matches: array<int, string>, updated: bool, untranslated_ids: list<string>}>
 */
function uamswp_t2p_update_shortcode_locations(): array
{
    global $wpdb;

    $id_map = uamswp_t2p_build_id_map();
    $locations = uamswp_t2p_scan_shortcode_locations();

    foreach ($locations as &$loc) {
        $untranslated = [];

        $updated = true;

        if ($loc['type'] === 'post') {
            $post = get_post($loc['id']);
            $content = $post === null ? null : uamswp_t2p_translate_id_attributes($post->post_content, $id_map, $untranslated);
            $content = $content === null ? null : uamswp_t2p_rename_shortcode_tags($content);

            // A post deleted since the scan, or content the regex engine could not process, is left as it is.
            if ($content === null) {
                $updated = false;
            } else {
                wp_update_post(
                    [
                        'ID' => $loc['id'],
                        'post_content' => $content,
                    ]
                );
            }
        } else {
            [$option_name, $key] = explode(':', $loc['id'], 2);
            $widgets = get_option($option_name);
            if (is_array($widgets) && isset($widgets[$key]) && is_array($widgets[$key])) {
                $field = isset($widgets[$key]['content']) ? 'content' : 'text';
                $stored = $widgets[$key][$field] ?? null;
                $text = is_string($stored) ? uamswp_t2p_translate_id_attributes($stored, $id_map, $untranslated) : null;
                $text = $text === null ? null : uamswp_t2p_rename_shortcode_tags($text);

                // Content the regex engine could not process is left as it is.
                if ($text === null) {
                    $updated = false;
                } else {
                    $widgets[$key][$field] = $text;
                    update_option($option_name, $widgets);
                }
            }
        }

        $loc['updated'] = $updated;
        $loc['untranslated_ids'] = $untranslated;
    }

    return $locations;
}

