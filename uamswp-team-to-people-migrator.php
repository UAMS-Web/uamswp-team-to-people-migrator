/* -----------------------------------------------------------------------
 * Field mapping
 *
 * Each entry: destination custom-field key => [source meta key, transform]
 * transform is a callback name in this file, or null for a direct copy.
 * These map to the *default* fields both plugins ship with. Anything on a
 * tshowcase post that isn't covered here (custom fields added via the
 * "Custom Fields" CSV setting, or the social-network fields that People
 * Showcase never turned on) is auto-detected separately and copied over
 * as raw postmeta with the _ps prefix so nothing is silently dropped -
 * see uamswp_t2p_get_unmapped_meta().
 * --------------------------------------------------------------------- */

/**
 * The default field map: People Showcase meta key => [Team Showcase meta
 * key, optional transform callback name].
 *
 * @return array<string, array{0: string, 1: string|null}>
 */
function uamswp_t2p_get_field_map(): array
{
    return [
        '_psposition' => ['_tsposition', null],
        '_psemail' => ['_tsemail', null],
        '_pslocation' => ['_tslocation', null],
        '_pstel' => ['_tstel', null],
        '_psfreehtml' => ['_tsfreehtml', null], // textarea -> wysiwyg, plain text/HTML copies fine
        '_pspersonal' => ['_tspersonal', null], // Personal Website -> Provider Profile URL (semantics differ, still closest match)
        '_pspersonalanchor' => ['_tspersonalanchor', null],
        '_psuser' => ['_tsuser', null],
        '_pstwitter' => ['_tstwitter', 'uamswp_t2p_transform_twitter'], // full URL -> username
        '_psyoutube' => ['_tsyoutube', null], // video/channel URL -> video URL
    ];
}

/**
 * Meta keys on the source post that should never be copied or flagged as
 * "extra" - they're either WP internals or auto-regenerated by the
 * destination plugin on save.
 *
 * @return list<string>
 */
function uamswp_t2p_get_skip_keys(): array
{
    return [
        '_ts_lastname',      // regenerated automatically by uamspeople_lastname_custom_field() on save
        '_edit_lock',
        '_edit_last',
        '_thumbnail_id',      // handled separately (featured image)
        '_tshowcase_page_template',
        '_wp_page_template',
    ];
}

/**
 * Reduces a stored Twitter value to the bare handle.
 *
 * @param  scalar|null  $value  the stored value, usually a profile URL
 */
function uamswp_t2p_transform_twitter($value): string
{
    // The file is not strict_types, so trim() coerces a scalar to a string itself and the cast changes nothing.
    // @pest-mutate-ignore:RemoveStringCast
    $value = trim((string) $value);
    // Team Showcase stored a full profile URL; People Showcase wants just the handle.
    $path = wp_parse_url($value, PHP_URL_PATH);
    if ($path) {
        // end() ignores the keys, so re-indexing the filtered segments changes nothing.
        // @pest-mutate-ignore:UnwrapArrayValues
        $parts = array_values(array_filter(explode('/', $path)));
        if ($parts !== []) {
            return end($parts);
        }
    }

    return ltrim($value, '@');
}

/**
 * Any postmeta on the source post starting with _ts that isn't in the
 * known field map and isn't in the skip list. Copied over verbatim with
 * a _ps prefix so the data survives, but flagged in the report since
 * these fields likely aren't wired up in the People Showcase UI unless
 * added via that plugin's "Custom Fields" setting.
 *
 * @param  int  $post_id  the source post
 * @return array<string, string>
 */
function uamswp_t2p_get_unmapped_meta($post_id): array
{
    $map = uamswp_t2p_get_field_map();
    $known_src = wp_list_pluck($map, 0);
    $skip = uamswp_t2p_get_skip_keys();
    $all_meta = get_post_meta($post_id);
    $unmapped = [];

    if (! is_array($all_meta)) {
        return $unmapped;
    }

    foreach ($all_meta as $key => $values) {
        // The file is not strict_types, so str_starts_with() coerces an integer key itself, and an integer key never starts with _ts, so nothing past the check sees it.
        // @pest-mutate-ignore:RemoveStringCast
        $key = (string) $key;
        if (! str_starts_with($key, '_ts')) {
            continue;
        }
        if (in_array($key, $known_src, true) || in_array($key, $skip, true)) {
            continue;
        }
        $first = is_array($values) ? ($values[0] ?? '') : '';
        $unmapped[$key] = is_scalar($first) ? (string) $first : '';
    }

    return $unmapped;
}

